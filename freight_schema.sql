-- SeaQuest Freight Desk — schema (private; approved CRM users only)
-- Apply in Supabase SQL editor, or via the management API. Reuses is_approved() from the CRM auth.

create table if not exists freight_providers (
  id          bigint generated by default as identity primary key,
  name        text not null,
  type        text not null check (type in ('forwarder','nvocc','customs_broker','drayage','3pl')),
  website     text,
  lanes       text[] default '{}',          -- e.g. {china_uswc, oman_us}
  services    text[] default '{}',          -- {ocean, customs, drayage, warehousing}
  license_no  text,                          -- FMC OTI # / CBP broker filer code
  notes       text,
  status      text default 'new' check (status in ('new','contacted','quoted','preferred','do_not_use')),
  source_url  text,
  created_at  timestamptz default now(),
  updated_at  timestamptz default now()
);

create table if not exists freight_contacts (
  id          bigint generated by default as identity primary key,
  provider_id bigint references freight_providers(id) on delete cascade,
  name        text,
  title       text,
  email       text,
  phone       text,
  source_url  text,
  source_date date,
  verified    boolean default false,
  created_at  timestamptz default now()
);

create table if not exists freight_rfqs (
  id             bigint generated by default as identity primary key,
  ref            text,
  origin_port    text default 'Xiamen, CN',
  entry_port     text default 'Los Angeles / Long Beach, CA',
  final_destination text,                    -- variable per deal (default San Diego)
  incoterm       text,
  container_type text,                        -- 20 | 40 | 40HC | LCL
  container_count int,
  commodity      text default 'Paper packaging',
  hs_code        text,
  weight_kg      numeric,
  volume_cbm     numeric,
  cargo_ready_date date,
  services       text[] default '{}',
  unit_count     numeric,                     -- units in the shipment, for landed-cost/unit
  product_unit_cost numeric,                  -- FOB product cost per unit (for landed cost)
  duty_pct       numeric default 0,           -- import duty % applied to FOB product value (US basis)
  us_entry_fees  boolean default true,         -- include MPF+HMF estimate in landed cost
  notes          text,
  status         text default 'draft',        -- draft | sent | quoting | decided
  created_by     uuid default auth.uid(),
  created_at     timestamptz default now()
);

create table if not exists freight_rfq_sends (
  id          bigint generated by default as identity primary key,
  rfq_id      bigint references freight_rfqs(id) on delete cascade,
  provider_id bigint references freight_providers(id) on delete cascade,
  contact_id  bigint references freight_contacts(id) on delete set null,
  draft_status text default 'none',           -- none | draft_saved | sent | replied
  gmail_draft_id text,
  created_at  timestamptz default now()
);

create table if not exists freight_quotes (
  id          bigint generated by default as identity primary key,
  rfq_id      bigint references freight_rfqs(id) on delete cascade,
  provider_id bigint references freight_providers(id) on delete set null,
  currency    text default 'USD',
  line_items  jsonb default '[]',             -- [{label, amount}]
  total       numeric,
  transit_days int,
  valid_until date,
  terms       text,
  notes       text,
  received_at date default now(),
  created_at  timestamptz default now()
);

-- Row Level Security: only approved CRM users (never public).
alter table freight_providers enable row level security;
alter table freight_contacts  enable row level security;
alter table freight_rfqs      enable row level security;
alter table freight_rfq_sends enable row level security;
alter table freight_quotes    enable row level security;

create policy freight_providers_rw on freight_providers for all to authenticated using (is_approved()) with check (is_approved());
create policy freight_contacts_rw  on freight_contacts  for all to authenticated using (is_approved()) with check (is_approved());
create policy freight_rfqs_rw      on freight_rfqs      for all to authenticated using (is_approved()) with check (is_approved());
create policy freight_rfq_sends_rw on freight_rfq_sends for all to authenticated using (is_approved()) with check (is_approved());
create policy freight_quotes_rw    on freight_quotes    for all to authenticated using (is_approved()) with check (is_approved());

create index if not exists freight_contacts_provider_idx on freight_contacts(provider_id);
create index if not exists freight_quotes_rfq_idx on freight_quotes(rfq_id);
create index if not exists freight_sends_rfq_idx on freight_rfq_sends(rfq_id);
create index if not exists freight_providers_type_idx on freight_providers(type);

